r"""Run the full experimental study and write the report's tables.

This is the reproducible replacement for the notebook's section 10. It runs
every method over the benchmark suite, records each run in the results store
(`results/runs.db`, one row per run with its git SHA), and writes the derived
tables that `generate_figures.py` and `report/report.tex` both read -- so no
number in the report is ever typed by hand.

Usage
-----
    python run_experiments.py                 # full study
    python run_experiments.py --quick         # 1 seed, short limits (~1 min)
    python run_experiments.py --tables-only   # rebuild tables from the store
    python run_experiments.py --suite zones   # the polygonal no-fly suite

Outputs
-------
    results/runs.db                  every run, append-only
    results/experiment_results.csv   one row per instance
    results/summary.csv              one row per method
    results/results.json             the same rows, for the figure script
    report/results_table.tex         \input-ed by report/report.tex
    report/summary_table.tex         \input-ed by report/report.tex
"""
from __future__ import annotations

import argparse
import csv
import json
import time
from pathlib import Path
from typing import Any, Dict, List, Sequence

from drp.eval.metrics import instance_rows, method_summary
from drp.eval.runner import run_study
from drp.eval.store import ResultStore, git_sha
from drp.instances import default_benchmark_suite, zone_benchmark_suite

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
REPORT = ROOT / "report"

METHOD_LABELS = {
    "greedy": "Greedy construction",
    "bnb": "Branch & Bound",
    "ga": "Genetic Algorithm",
    "sa": "Simulated Annealing",
    "alns": "ALNS",
}


def tex_escape(s: str) -> str:
    """Escape the LaTeX specials that occur in our instance and method names."""
    return s.replace("&", r"\&").replace("_", r"\_").replace("%", r"\%")


def write_csvs(recs: Sequence[Dict[str, Any]],
               summary: Sequence[Dict[str, Any]]) -> None:
    RESULTS.mkdir(exist_ok=True)

    fields: List[str] = []
    for r in recs:
        for k in r:
            if k not in fields:
                fields.append(k)
    with (RESULTS / "experiment_results.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(recs)

    with (RESULTS / "summary.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(summary[0].keys()))
        w.writeheader()
        w.writerows(summary)

    (RESULTS / "results.json").write_text(json.dumps(recs, indent=2), encoding="utf-8")


def write_latex_tables(recs: Sequence[Dict[str, Any]],
                       summary: Sequence[Dict[str, Any]],
                       methods: Sequence[str]) -> None:
    """Emit the report tables so report.tex never quotes a stale number."""
    REPORT.mkdir(exist_ok=True)
    show = [m for m in ("greedy", "bnb", "ga", "sa", "alns") if m in methods]

    header = (r"Instance & $n$ & $K$ & "
              + " & ".join(tex_escape(METHOD_LABELS[m].split()[0]) for m in show)
              + r" & Opt? & Ref \\")
    lines = [
        "% Generated by run_experiments.py -- do not edit by hand.",
        r"\begin{tabular}{lrr" + "r" * len(show) + r"cr}",
        r"\toprule", header, r"\midrule",
    ]
    for r in recs:
        cells = []
        for m in show:
            v = r.get(f"{m}_best")
            cells.append("--" if v is None else f"{v:.1f}")
        lines.append(
            f"{tex_escape(r['instance'])} & {r['n']} & {r['K']} & "
            + " & ".join(cells)
            + f" & {'yes' if r.get('bnb_opt') else 'no'}"
            + f" & {r['ref']:.1f} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    (REPORT / "results_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    n_proven = sum(1 for r in recs if r.get("bnb_opt"))
    lines = [
        "% Generated by run_experiments.py -- do not edit by hand.",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Method & Instances & Avg.\ energy & Avg.\ time (s) & Optima found \\",
        r"\midrule",
    ]
    for s in summary:
        lines.append(
            f"{tex_escape(METHOD_LABELS.get(s['method'], s['method']))} & "
            f"{s['instances_solved']} & {s['avg_energy'] or 0:.1f} & "
            f"{s['avg_time_s']:.2f} & {s['optima_found']}/{n_proven} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    (REPORT / "summary_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote report/results_table.tex and report/summary_table.tex")


def report(recs, summary, methods) -> None:
    print("\n" + "-" * 78)
    head = f"{'instance':14s} {'n':>3s} " + "".join(f"{m:>10s}" for m in methods)
    print(head)
    print("-" * 78)
    for r in recs:
        row = f"{r['instance']:14s} {r['n']:>3d} "
        for m in methods:
            v = r.get(f"{m}_best")
            row += f"{'--':>10s}" if v is None else f"{v:>10.1f}"
        row += "   proved" if r.get("bnb_opt") else ""
        print(row)
    print("-" * 78)
    print(f"{'method':22s} {'avg energy':>11s} {'avg time':>9s} {'optima':>9s} {'gap%':>8s}")
    for s in summary:
        gap = s["avg_gap_pct_on_proven"]
        print(f"{METHOD_LABELS.get(s['method'], s['method']):22s} "
              f"{s['avg_energy'] or 0:11.1f} {s['avg_time_s']:9.2f} "
              f"{s['optima_found']:>4d}/{s['n_proven']:<4d} "
              f"{'--' if gap is None else f'{gap:8.3f}'}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--bnb-time", type=float, default=20.0)
    ap.add_argument("--meta-time", type=float, default=5.0)
    ap.add_argument("--methods", default="greedy,bnb,ga,sa,alns")
    ap.add_argument("--suite", default="default", choices=["default", "zones"])
    ap.add_argument("--store", default="results/runs.db")
    ap.add_argument("--quick", action="store_true",
                    help="fast smoke run: 1 seed, 3s B&B, 1s per metaheuristic")
    ap.add_argument("--tables-only", action="store_true",
                    help="rebuild the tables from the store without re-solving")
    ap.add_argument("--group", help="which stored run group to tabulate")
    args = ap.parse_args()

    methods = [m.strip() for m in args.methods.split(",") if m.strip()]

    if args.tables_only:
        store = ResultStore(args.store)
        group = args.group or store.latest_group()
        if group is None:
            raise SystemExit(f"{args.store} is empty -- run the study first.")
        rows = store.rows(group)
        recs, summary = instance_rows(rows), method_summary(rows)
        write_csvs(recs, summary)
        write_latex_tables(recs, summary, store.methods(group))
        report(recs, summary, store.methods(group))
        print(f"\nrebuilt tables from group {group} ({len(rows)} runs)")
        store.close()
        return 0

    if args.quick:
        args.seeds, args.bnb_time, args.meta_time = 1, 3.0, 1.0

    suite = (zone_benchmark_suite() if args.suite == "zones"
             else default_benchmark_suite())
    seeds = list(range(1, args.seeds + 1))

    print(f"{len(suite)} instances | methods={methods} | seeds={seeds}")
    print(f"B&B {args.bnb_time}s | metaheuristics {args.meta_time}s/seed | "
          f"code {git_sha()}")

    t0 = time.time()
    store = run_study(suite, methods=methods, seeds=seeds,
                      time_limit=args.meta_time, bnb_time_limit=args.bnb_time,
                      store=ResultStore(args.store), progress=print)
    group = store.latest_group()
    rows = store.rows(group)
    recs, summary = instance_rows(rows), method_summary(rows)

    write_csvs(recs, summary)
    write_latex_tables(recs, summary, methods)
    report(recs, summary, methods)
    print(f"\nfinished in {time.time() - t0:.1f}s -> results/ (group {group})")
    store.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
