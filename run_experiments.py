r"""Run the full experimental study and write the report's tables.

This is the reproducible replacement for the notebook's section 10. It runs
every method over the benchmark suite, records each run in the results store
(`results/runs.db`, one row per run with its git SHA), and writes the derived
tables that `generate_figures.py` and `report/report.tex` both read -- so no
number in the report is ever typed by hand.

Usage
-----
    python run_experiments.py                 # full study
    python run_experiments.py --quick         # 1 seed, short limits (~1 min)
    python run_experiments.py --tables-only   # rebuild tables from the store
    python run_experiments.py --suite zones   # the polygonal no-fly suite
    python run_experiments.py --suite geo     # the real Pontianak geography

Outputs
-------
    results/runs.db                  every run, append-only
    results/<suite>_runs.db          side suites keep their own store, so
                                     they never become the report's numbers
    results/experiment_results.csv   one row per instance
    results/summary.csv              one row per method
    results/results.json             the same rows, for the figure script
    results/significance.json        roadmap §6: bootstrap CIs, Friedman, pairwise Wilcoxon
    report/results_table.tex         \input-ed by report/report.tex
    report/summary_table.tex         \input-ed by report/report.tex
    report/significance_table.tex    \input-ed by report/report.tex
"""
from __future__ import annotations

import argparse
import csv
import json
import time
from pathlib import Path
from typing import Any, Dict, List, Sequence

from drp.eval.metrics import instance_rows, method_summary
from drp.eval.runner import run_study
from drp.eval.stats import SignificanceReport, significance_report
from drp.eval.store import ResultStore, git_sha
from drp.instances import (default_benchmark_suite, geo_benchmark_suite,
                           zone_benchmark_suite)

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
REPORT = ROOT / "report"

METHOD_LABELS = {
    "greedy": "Greedy construction",
    "bnb": "Branch & Bound",
    "ga": "Genetic Algorithm",
    "sa": "Simulated Annealing",
    "alns": "ALNS",
}


def tex_escape(s: str) -> str:
    """Escape the LaTeX specials that occur in our instance and method names."""
    return s.replace("&", r"\&").replace("_", r"\_").replace("%", r"\%")


def write_csvs(recs: Sequence[Dict[str, Any]],
               summary: Sequence[Dict[str, Any]]) -> None:
    RESULTS.mkdir(exist_ok=True)

    fields: List[str] = []
    for r in recs:
        for k in r:
            if k not in fields:
                fields.append(k)
    with (RESULTS / "experiment_results.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(recs)

    with (RESULTS / "summary.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(summary[0].keys()))
        w.writeheader()
        w.writerows(summary)

    (RESULTS / "results.json").write_text(json.dumps(recs, indent=2), encoding="utf-8")


def write_significance_json(sig: SignificanceReport) -> None:
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "significance.json").write_text(
        json.dumps(sig.to_dict(), indent=2), encoding="utf-8")


def write_significance_table(sig: SignificanceReport) -> None:
    """Roadmap §6: Friedman + Nemenyi critical difference, and every pairwise
    Wilcoxon comparison -- so a claim like "ALNS is better" is backed by a
    p-value, not just a smaller mean in a table."""
    REPORT.mkdir(exist_ok=True)
    fr = sig.friedman
    lines = ["% Generated by run_experiments.py -- do not edit by hand."]

    lines += [r"\begin{tabular}{lrr}", r"\toprule",
              r"Method & Avg.\ rank & Mean gap \%\ [95\% CI] \\", r"\midrule"]
    ranks = fr.avg_ranks if fr else {}
    for m in sig.methods:
        rank = ranks.get(m)
        mean, lo, hi = sig.method_ci.get(m, (float("nan"),) * 3)
        rank_cell = "--" if rank is None else f"{rank:.2f}"
        lines.append(
            f"{tex_escape(METHOD_LABELS.get(m, m))} & {rank_cell} & "
            f"{mean:.2f} [{lo:.2f}, {hi:.2f}] \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    if fr and fr.statistic is not None:
        lines += [
            "", f"% Friedman $\\chi^2$ = {fr.statistic:.2f}, "
            f"$p$ = {fr.p_value:.4g}, $n$ = {fr.n_instances} instances, "
            f"Nemenyi CD (\\alpha=0.05) = {fr.critical_difference:.3f}",
        ]

    lines += ["", r"\begin{tabular}{llrrrl}", r"\toprule",
              r"A & B & $n$ & Statistic & $p$ & Result \\", r"\midrule"]
    for w in sig.pairwise:
        if w.p_value is None:
            result = "not testable"
        elif w.significant:
            result = f"{tex_escape(METHOD_LABELS.get(w.better, w.better or '--'))} better"
        else:
            result = "no sig. difference"
        stat_cell = "--" if w.statistic is None else f"{w.statistic:.1f}"
        p_cell = "--" if w.p_value is None else f"{w.p_value:.4g}"
        lines.append(
            f"{tex_escape(METHOD_LABELS.get(w.method_a, w.method_a))} & "
            f"{tex_escape(METHOD_LABELS.get(w.method_b, w.method_b))} & "
            f"{w.n} & {stat_cell} & {p_cell} & {result} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    (REPORT / "significance_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote report/significance_table.tex")


def report_significance(sig: SignificanceReport) -> None:
    print("\n" + "-" * 78)
    print(f"significance (metric: {sig.metric}, alpha: {sig.alpha}, "
          f"n={sig.n_instances} instances)")
    print("-" * 78)
    fr = sig.friedman
    if fr and fr.statistic is not None:
        print(f"Friedman: chi2={fr.statistic:.2f} p={fr.p_value:.4g}  "
              f"Nemenyi CD={fr.critical_difference:.3f}")
    for m in sig.methods:
        rank = (fr.avg_ranks.get(m) if fr else None)
        mean, lo, hi = sig.method_ci.get(m, (float("nan"),) * 3)
        rank_s = "--" if rank is None else f"{rank:5.2f}"
        print(f"  {METHOD_LABELS.get(m, m):22s} avg rank={rank_s}  "
              f"mean gap%={mean:7.2f}  95% CI=[{lo:7.2f}, {hi:7.2f}]")
    for w in sig.pairwise:
        if w.p_value is None:
            continue
        tag = ("sig, " + METHOD_LABELS.get(w.better, w.better or "--") + " better"
              if w.significant else "not significant")
        print(f"  {w.method_a:8s} vs {w.method_b:8s}  n={w.n:2d}  "
              f"p={w.p_value:.4g}  {tag}")


def write_latex_tables(recs: Sequence[Dict[str, Any]],
                       summary: Sequence[Dict[str, Any]],
                       methods: Sequence[str]) -> None:
    """Emit the report tables so report.tex never quotes a stale number."""
    REPORT.mkdir(exist_ok=True)
    show = [m for m in ("greedy", "bnb", "ga", "sa", "alns") if m in methods]

    header = (r"Instance & $n$ & $K$ & "
              + " & ".join(tex_escape(METHOD_LABELS[m].split()[0]) for m in show)
              + r" & Opt? & Ref \\")
    lines = [
        "% Generated by run_experiments.py -- do not edit by hand.",
        r"\begin{tabular}{lrr" + "r" * len(show) + r"cr}",
        r"\toprule", header, r"\midrule",
    ]
    for r in recs:
        cells = []
        for m in show:
            v = r.get(f"{m}_best")
            cells.append("--" if v is None else f"{v:.1f}")
        lines.append(
            f"{tex_escape(r['instance'])} & {r['n']} & {r['K']} & "
            + " & ".join(cells)
            + f" & {'yes' if r.get('bnb_opt') else 'no'}"
            + f" & {r['ref']:.1f} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    (REPORT / "results_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    n_proven = sum(1 for r in recs if r.get("bnb_opt"))
    lines = [
        "% Generated by run_experiments.py -- do not edit by hand.",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Method & Instances & Avg.\ energy & Avg.\ time (s) & Optima found \\",
        r"\midrule",
    ]
    for s in summary:
        lines.append(
            f"{tex_escape(METHOD_LABELS.get(s['method'], s['method']))} & "
            f"{s['instances_solved']} & {s['avg_energy'] or 0:.1f} & "
            f"{s['avg_time_s']:.2f} & {s['optima_found']}/{n_proven} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    (REPORT / "summary_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote report/results_table.tex and report/summary_table.tex")


def report(recs, summary, methods) -> None:
    print("\n" + "-" * 78)
    head = f"{'instance':14s} {'n':>3s} " + "".join(f"{m:>10s}" for m in methods)
    print(head)
    print("-" * 78)
    for r in recs:
        row = f"{r['instance']:14s} {r['n']:>3d} "
        for m in methods:
            v = r.get(f"{m}_best")
            row += f"{'--':>10s}" if v is None else f"{v:>10.1f}"
        row += "   proved" if r.get("bnb_opt") else ""
        print(row)
    print("-" * 78)
    print(f"{'method':22s} {'avg energy':>11s} {'avg time':>9s} {'optima':>9s} {'gap%':>8s}")
    for s in summary:
        gap = s["avg_gap_pct_on_proven"]
        print(f"{METHOD_LABELS.get(s['method'], s['method']):22s} "
              f"{s['avg_energy'] or 0:11.1f} {s['avg_time_s']:9.2f} "
              f"{s['optima_found']:>4d}/{s['n_proven']:<4d} "
              f"{'--' if gap is None else f'{gap:8.3f}'}")


def imported_suite(args) -> List[Any]:
    """Load a literature benchmark set from disk (roadmap §3.3).

    The instances keep the importer's faithful defaults -- ``beta = 0``, an
    unbounded battery, and for CVRPLIB the rounded ``EUC_2D`` metric -- so what
    runs here is the published problem, and its objective is comparable to the
    published optimum.
    """
    from drp.instances import benchmark_directory

    default_dir = "data/CVRPLIB" if args.suite == "cvrplib" else "data/Solomon"
    root = Path(args.benchmark_dir or default_dir)
    if not root.exists():
        raise SystemExit(
            f"{root} does not exist. Benchmark files are not committed (they "
            "are third-party data); fetch them from "
            "http://vrp.galgos.inf.puc-rio.br (CVRPLIB) or "
            "https://www.sintef.no/projectweb/top/vrptw/solomon-benchmark/ "
            "and point --benchmark-dir at them.")

    pattern = "*.vrp" if args.suite == "cvrplib" else "*.txt"
    kwargs: Dict[str, Any] = {}
    if args.suite == "solomon" and args.customers:
        kwargs["n_customers"] = args.customers

    imported = benchmark_directory(root, pattern=pattern, fmt=args.suite,
                                   limit=args.limit, **kwargs)
    dropped = sorted({note for imp in imported for note in imp.dropped})
    print(f"{len(imported)} instances from {root} "
          f"(n = {imported[0].instance.n_customers}"
          f"..{imported[-1].instance.n_customers})")
    if dropped:
        print("dropped from every instance: " + "; ".join(dropped))
    return [imp.instance for imp in imported]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--bnb-time", type=float, default=20.0)
    ap.add_argument("--meta-time", type=float, default=5.0)
    ap.add_argument("--methods", default="greedy,bnb,ga,sa,alns")
    ap.add_argument("--suite", default="default",
                    choices=["default", "zones", "geo", "cvrplib", "solomon"],
                    help="synthetic (the study of record), synthetic with "
                         "no-fly zones, the real Pontianak geography, or an "
                         "imported literature set (roadmap §3.3)")
    ap.add_argument("--benchmark-dir",
                    help="where the .vrp / Solomon files live "
                         "(default: data/CVRPLIB or data/Solomon)")
    ap.add_argument("--customers", type=int,
                    help="solomon only: keep the first N customers of each file")
    ap.add_argument("--limit", type=int,
                    help="use only the first N instances, smallest first")
    ap.add_argument("--store", default=None,
                    help="results database (default: results/runs.db for the "
                         "default suite, results/<suite>_runs.db otherwise)")
    ap.add_argument("--quick", action="store_true",
                    help="fast smoke run: 1 seed, 3s B&B, 1s per metaheuristic")
    ap.add_argument("--tables-only", action="store_true",
                    help="rebuild the tables from the store without re-solving")
    ap.add_argument("--group", help="which stored run group to tabulate")
    args = ap.parse_args()

    methods = [m.strip() for m in args.methods.split(",") if m.strip()]
    # Side suites keep their own store. Sharing one would make them the "latest
    # group", and `--tables-only` would then quietly rebuild the report's tables
    # from a run the report is not about.
    if args.store is None:
        args.store = ("results/runs.db" if args.suite == "default"
                      else f"results/{args.suite}_runs.db")

    if args.tables_only:
        store = ResultStore(args.store)
        group = args.group or store.latest_group()
        if group is None:
            raise SystemExit(f"{args.store} is empty -- run the study first.")
        rows = store.rows(group)
        recs, summary = instance_rows(rows), method_summary(rows)
        sig = significance_report(rows, methods=store.methods(group))
        write_csvs(recs, summary)
        write_latex_tables(recs, summary, store.methods(group))
        write_significance_json(sig)
        write_significance_table(sig)
        report(recs, summary, store.methods(group))
        report_significance(sig)
        print(f"\nrebuilt tables from group {group} ({len(rows)} runs)")
        store.close()
        return 0

    if args.quick:
        args.seeds, args.bnb_time, args.meta_time = 1, 3.0, 1.0

    if args.suite in ("cvrplib", "solomon"):
        suite = imported_suite(args)
    else:
        suites = {"default": default_benchmark_suite,
                  "zones": zone_benchmark_suite,
                  "geo": geo_benchmark_suite}
        suite = suites[args.suite]()
    seeds = list(range(1, args.seeds + 1))

    print(f"{len(suite)} instances | methods={methods} | seeds={seeds}")
    print(f"B&B {args.bnb_time}s | metaheuristics {args.meta_time}s/seed | "
          f"code {git_sha()}")

    t0 = time.time()
    store = run_study(suite, methods=methods, seeds=seeds,
                      time_limit=args.meta_time, bnb_time_limit=args.bnb_time,
                      store=ResultStore(args.store), progress=print)
    group = store.latest_group()
    rows = store.rows(group)
    recs, summary = instance_rows(rows), method_summary(rows)
    sig = significance_report(rows, methods=methods)

    if args.suite == "default":
        write_csvs(recs, summary)
        write_latex_tables(recs, summary, methods)
        write_significance_json(sig)
        write_significance_table(sig)
    report(recs, summary, methods)
    report_significance(sig)
    if args.suite != "default":
        print(f"\n({args.suite} suite: stored in {args.store}, and the report's "
              "tables were left alone -- they describe the default suite.)")
    print(f"\nfinished in {time.time() - t0:.1f}s -> results/ (group {group})")
    store.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
