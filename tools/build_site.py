"""Regenerate the project site's data files from the committed instance and solution.

    python tools/build_site.py

writes

    site/data/instance.js   the instance (geo.json) and the routes of its solution (sol.json)
    site/data/basemap.js    the OSM basemap, projected and simplified for the hero chart

Nothing on the site is typed by hand: every number it shows is either in these two files
or computed from them in the browser with the same energy function the solvers use.

The basemap needs ``data/osm/pontianak_south_basemap.json``, which is git-ignored with the
rest of ``data/osm/``. Without it the script keeps the committed ``basemap.js`` and says so.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import List, Sequence, Tuple

ROOT = Path(__file__).resolve().parent.parent

# The chart frame. site/js/model.js projects with the same three numbers; change both.
LON0, LAT0 = 109.296, -0.024     # top-left corner of the sheet
WIDTH_DEG, HEIGHT_DEG = 0.054, 0.060
SCALE = 1000 / WIDTH_DEG          # viewBox units per degree; equirectangular is exact enough at 0°


def project(lat: float, lon: float) -> Tuple[float, float]:
    return (lon - LON0) * SCALE, (LAT0 - lat) * SCALE


def rdp(pts: List[Tuple[float, float]], eps: float) -> List[Tuple[float, float]]:
    """Ramer-Douglas-Peucker simplification, tolerance in viewBox units."""
    if len(pts) < 3:
        return pts
    (ax, ay), (bx, by) = pts[0], pts[-1]
    dx, dy = bx - ax, by - ay
    length = math.hypot(dx, dy) or 1e-9
    worst, worst_d = 0, 0.0
    for k in range(1, len(pts) - 1):
        d = abs(dy * (pts[k][0] - ax) - dx * (pts[k][1] - ay)) / length
        if d > worst_d:
            worst, worst_d = k, d
    if worst_d > eps:
        return rdp(pts[:worst + 1], eps)[:-1] + rdp(pts[worst:], eps)
    return [pts[0], pts[-1]]


def svg_path(lines: Sequence[Sequence[Sequence[float]]], height: float,
             eps: float, close: bool = False) -> str:
    out = []
    for line in lines:
        pts = [project(p[0], p[1]) for p in line]
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        if max(xs) < -30 or min(xs) > 1030 or max(ys) < -30 or min(ys) > height + 30:
            continue
        pts = rdp(pts, eps)
        out.append("M" + "L".join(f"{round(x)} {round(y)}" for x, y in pts) + ("Z" if close else ""))
    return "".join(out)


def build_basemap(src: Path) -> dict:
    b = json.loads(src.read_text(encoding="utf-8"))
    height = round(HEIGHT_DEG * SCALE)
    places = []
    for p in b["places"]:
        x, y = project(p["lat"], p["lon"])
        places.append({"n": p["name"], "k": p["kind"], "x": round(x), "y": round(y)})
    places.sort(key=lambda p: p["k"] != "city")
    return {
        "H": height,
        "street": svg_path(b["roads"]["street"], height, 1.2),
        "secondary": svg_path(b["roads"]["secondary"], height, 0.8),
        "arterial": svg_path(b["roads"]["arterial"], height, 0.8),
        "waterl": svg_path(b["water"]["lines"], height, 0.8),
        "watera": svg_path(b["water"]["areas"], height, 0.8, close=True),
        "green": svg_path(b["green"], height, 1.0, close=True),
        "built": svg_path(b["built"], height, 0.6, close=True),
        "places": places,
        "bounds_top_y": round((LAT0 - b["bounds"][2]) * SCALE),
    }


def build_instance(instance: Path, solution: Path) -> dict:
    g = json.loads(instance.read_text(encoding="utf-8"))
    s = json.loads(solution.read_text(encoding="utf-8"))
    if s.get("instance") != g.get("name"):
        raise SystemExit(f"{solution} solves {s.get('instance')!r}, not {g.get('name')!r}")
    return {
        "alpha": g["energy"]["alpha"],
        "beta": g["energy"]["beta"],
        "battery": g["fleet"]["battery"],
        "payload": g["fleet"]["payload"],
        "depot": g["depot"],
        "customers": g["customers"],
        "nofly": g["nofly"]["polygons"][0],
        "routes": [r["customers"] for r in s["routes"]],
    }


def write_js(path: Path, name: str, data: dict, source: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(data, separators=(",", ":"))
    path.write_text(f"// Generated by tools/build_site.py from {source}. Do not edit.\n"
                    f"const {name} = {body};\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size:,} bytes)")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--instance", type=Path, default=ROOT / "geo.json")
    ap.add_argument("--solution", type=Path, default=ROOT / "sol.json")
    ap.add_argument("--basemap", type=Path, default=ROOT / "data/osm/pontianak_south_basemap.json")
    ap.add_argument("--out", type=Path, default=ROOT / "site/data")
    args = ap.parse_args()

    write_js(args.out / "instance.js", "D", build_instance(args.instance, args.solution),
             f"{args.instance.name} and {args.solution.name}")
    if args.basemap.exists():
        write_js(args.out / "basemap.js", "BM", build_basemap(args.basemap),
                 f"{args.basemap.name} (© OpenStreetMap contributors, ODbL)")
    else:
        print(f"{args.basemap} not found; keeping the committed basemap.js")


if __name__ == "__main__":
    main()
